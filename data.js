// Helper: Get stat labels for a position
function getStatLabels(pos) {
  switch(pos) {
    case 'QB':   return ['YDS','TD','INT','RTG'];
    case 'RB':   return ['YDS','TD','YPC','REC'];
    case 'WR':   return ['REC','YDS','TD','YPR'];
    case 'EDGE': return ['SCK','TFL','FF','TKL'];
    case 'LB':   return ['TKL','SCK','INT','FF'];
    case 'DB':   return ['INT','PD','TKL','FF'];
    case 'K':    return ['FGM','FG%','LNG','PTS'];
    default:     return [];
  }
}

// Helper: Get stat values for a player
function getStatValues(player) {
  const s = player.stats;
  switch(player.pos) {
    case 'QB':   return [s.yds, s.td, s.int, s.rtg];
    case 'RB':   return [s.yds, s.td, s.ypc, s.rec];
    case 'WR':   return [s.rec, s.yds, s.td, s.ypr];
    case 'EDGE': return [s.sck, s.tfl, s.ff, s.tkl];
    case 'LB':   return [s.tkl, s.sck, s.int, s.ff];
    case 'DB':   return [s.int, s.pd, s.tkl, s.ff];
    case 'K':    return [s.fgm, s.pct, s.lng, s.pts];
    default:     return [];
  }
}

