// Helper: Get valid team-decade combos that have players
function getValidCombos() {
  const combos = new Set();
  PLAYERS.forEach(p => combos.add(`${p.team}|${p.decade}`));
  return Array.from(combos).map(c => {
    const [team, decade] = c.split('|');
    return { team, decade };
  });
}

