function getPrimeYear(player) {
  const key = `${player.name}|${player.team}|${player.decade}`;
  if (PRIME_YEARS[key]) return PRIME_YEARS[key];
  const starts = {"60s":1960,"70s":1970,"80s":1980,"90s":1990,"00s":2000,"10s":2010,"20s":2020};
  const start = starts[player.decade] || 2000;
  const max = player.decade === "20s" ? 2025 : start + 9;
  let hash = 0;
  for (let i = 0; i < player.name.length; i++) hash = ((hash << 5) - hash) + player.name.charCodeAt(i);
  return start + (Math.abs(hash) % (max - start + 1));
}
