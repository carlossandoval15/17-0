# Stats templates by position (role-player level)
def make_stats(pos, decade):
    era_mult = {"60s":0.82,"70s":0.88,"80s":0.92,"90s":0.96,"00s":1.0,"10s":1.04,"20s":1.06}.get(decade, 1.0)
    if pos == "QB":
        return {"yds":int(2800*era_mult),"td":int(16*era_mult),"int":14,"rtg":round(76*era_mult,1)}
    elif pos == "RB":
        return {"yds":int(900*era_mult),"td":int(7*era_mult),"ypc":4.0,"rec":int(25*era_mult)}
    elif pos == "WR":
        return {"rec":int(55*era_mult),"yds":int(820*era_mult),"td":int(5*era_mult),"ypr":round(14.2,1)}
    elif pos == "K":
        return {"fgm":int(22*era_mult),"pct":round(76*era_mult,1),"lng":48,"pts":int(95*era_mult)}
    elif pos == "EDGE":
        return {"sck":round(7*era_mult,1),"tfl":int(11*era_mult),"ff":2,"tkl":int(55*era_mult)}
    elif pos == "LB":
        return {"tkl":int(95*era_mult),"sck":3,"int":2,"ff":2}
    elif pos == "DB":
        return {"int":3,"pd":int(10*era_mult),"tkl":int(55*era_mult),"ff":1}

# OVR by position (role players 74-82)
def make_ovr(pos, name):
    h = int(hashlib.md5(name.encode()).hexdigest()[:4], 16)
    return 74 + (h % 9)  # 74-82

