lines.append("  // ========== GAP FILLS (auto-generated) ==========")
for gap in GAPS:
    team, decade, pos = gap.split("|")
    name = KNOWN.get(gap)
    if not name:
        name = f"Player {gap}"
    ovr = make_ovr(pos, name)
    stats = make_stats(pos, decade)
    stats_str = json.dumps(stats).replace('"', '')
    # Convert stats keys to unquoted JS
    stats_js = "{" + ",".join(f"{k}:{v}" for k,v in stats.items()) + "}"
    lines.append(f'  {{name:"{name}",team:"{team}",decade:"{decade}",pos:"{pos}",stats:{stats_js},ovr:{ovr}}},')

print("\n".join(lines))
